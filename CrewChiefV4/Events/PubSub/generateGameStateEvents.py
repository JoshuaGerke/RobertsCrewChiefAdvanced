#!/usr/bin/env python3
"""Generate Crew Chief game events from the authoritative XLSX workbook.

Usage: python generateGameStateEvents.py [GameStateEvents.xlsx]
Requires: pip install openpyxl
"""
import csv
import re
import sys
from pathlib import Path
from openpyxl import load_workbook

NAMESPACE = 'CrewChiefV4.Events.PubSub'
OPERATORS = {'becomesTrue', 'becomesFalse', 'changes', 'isSet', 'increases'}
IDENT = re.compile(r'^[A-Za-z_][A-Za-z_0-9]*$')
PATH = re.compile(r'^[A-Za-z_][A-Za-z_0-9]*(\.[A-Za-z_][A-Za-z_0-9]*)*$')
MARKER = '        // <NEW CUSTOM DETECTORS - generator inserts above this line>'


def write_if_changed(path, contents):
    if not path.exists() or path.read_text(encoding='utf-8') != contents:
        path.write_text(contents, encoding='utf-8', newline='\n')
        print('Updated:', path.name)


def read_events(xlsx):
    wb = load_workbook(xlsx, read_only=True, data_only=True)
    try:
        ws = wb.active
        rows = ws.iter_rows(values_only=True)
        header = next(rows, None)
        if not header or [str(v or '').strip().lower() for v in header[:3]] != ['event', 'gamestate property', 'condition']:
            raise ValueError('First row must be: Event, GameState Property, Condition')
        events = []
        seen = set()
        for rownum, row in enumerate(rows, 2):
            values = [str(row[i]).strip() if len(row) > i and row[i] is not None else '' for i in range(3)]
            name, prop, op = values
            if not any(values):
                continue
            if not IDENT.fullmatch(name):
                raise ValueError(f'Row {rownum}: invalid event name {name!r}')
            if name in seen:
                raise ValueError(f'Row {rownum}: duplicate event {name}')
            seen.add(name)
            if bool(prop) != bool(op):
                raise ValueError(f'Row {rownum}: property and condition must both be present or both blank')
            if prop and (not PATH.fullmatch(prop) or op not in OPERATORS):
                raise ValueError(f'Row {rownum}: invalid property or condition: {prop!r}, {op!r}')
            events.append((name, prop, op))
        if not events:
            raise ValueError('No events found')
        return sorted(events, key=lambda e: e[0])
    finally:
        wb.close()


def expression(prop, op):
    p, c = f'pgs.{prop}', f'cgs.{prop}'
    return {'becomesTrue': f'!{p} && {c}',
            'becomesFalse': f'{p} && !{c}',
            'changes': f'{p} != {c}',
            'increases': f'{c} > {p}',
            'isSet': c}[op]


def generate(events, folder):
    csvpath = folder / 'GameStateEvents.csv'
    import io
    buf = io.StringIO(newline='')
    writer = csv.writer(buf, lineterminator='\n')
    writer.writerow(['Event', 'Property', 'Condition'])
    writer.writerows(events)
    write_if_changed(csvpath, buf.getvalue())

    enum_lines = ['// <auto-generated> From GameStateEvents.xlsx. Do not edit. </auto-generated>',
                  f'namespace {NAMESPACE}', '{', '    /// <summary>', '    /// Generic game events that are published to subscribed handlers', '    /// </summary>', '    public enum GameEvent', '    {']
    enum_lines.extend(f'        {name},' for name, _, _ in events)
    enum_lines += ['    }', '}', '']
    write_if_changed(folder / 'GameEvent.Generated.cs', '\n'.join(enum_lines))

    bool_lines = ['// <auto-generated> From GameStateEvents.xlsx. Do not edit. </auto-generated>',
                  f'namespace {NAMESPACE}', '{', '    /// <summary>', '    /// One for each game event that is detected, contains the current ', '    /// state of the event as detected in the current tick', '    /// </summary>', '    public static class GameEventBool', '    {']
    bool_lines.extend(f'        public static bool {name} {{ get; internal set; }}' for name, _, _ in events)
    bool_lines += ['    }', '}', '']
    write_if_changed(folder / 'GameEventBool.Generated.cs', '\n'.join(bool_lines))

    lines = ['// <auto-generated> From GameStateEvents.xlsx. Do not edit. </auto-generated>',
             'using CrewChiefV4.GameState;',
             f'namespace {NAMESPACE}', '{', '    public partial class GameStateEventDetector', '    {',
             '        private void DetectEvents(GameStateData pgs, GameStateData cgs)', '        {',
             '            // Every detector assigns its own GameEventBool each tick.']
    lines.extend(f'            Detect{name}(pgs, cgs);' for name, _, _ in events)
    lines += ['        }', '',
              '        private void ResetEventBools()',
              '        {']
    lines.extend(f'            GameEventBool.{name} = false;' for name, _, _ in events)
    lines += ['        }', '']
    for name, prop, op in events:
        if not prop:
            continue
        lines += [f'        private void Detect{name}(GameStateData pgs, GameStateData cgs)',
                  '        {', f'            GameEventBool.{name} = {expression(prop, op)};',
                  f'            if (GameEventBool.{name})', '            {',
                  f'                EventBus.Publish(GameEvent.{name}, cgs);',
                  '            }', '        }', '']
    lines += ['    }', '}', '']
    write_if_changed(folder / 'GameStateEventDetector.Generated.cs', '\n'.join(lines))

    custom_path = folder / 'GameStateEventDetector.Custom.cs'
    if custom_path.exists():
        custom = custom_path.read_text(encoding='utf-8')
        if MARKER not in custom:
            raise ValueError(f'{custom_path.name} missing insertion marker; refusing to alter handwritten code')
    else:
        custom = (f'namespace {NAMESPACE}\n{{\n    public partial class GameStateEventDetector\n    {{\n'
                  f'        // The boilerplate for this is provided by the generator, implement the\n'
                  f'        // detection logic to replace the #error.\n\n'
                  f'{MARKER}\n    }}\n}}\n')
    comment = ('        // The boilerplate for this is provided by the generator, implement the\n'
               '        // detection logic to replace the #error.')
    if comment not in custom:
        custom = custom.replace(MARKER, comment + '\n\n' + MARKER)
    # Detect existing declarations; don't mistake generated calls for declarations.
    declaration = re.compile(r'\b(?:private|internal|protected|public)\s+void\s+Detect([A-Za-z_][A-Za-z_0-9]*)\s*\(')
    existing = set(declaration.findall(custom))
    new = []
    for name, prop, _ in events:
        if not prop and name not in existing:
            new += [f'        private void Detect{name}(GameStateData pgs, GameStateData cgs)',
                    '        {', f'#error Implement Detect{name}',
                    f'            // EventBus.Publish(GameEvent.{name}, cgs);',
                    '        }', '']
            print('Custom implementation required:', name)
    if new:
        custom = custom.replace(MARKER, '\n'.join(new) + '\n' + MARKER)
    write_if_changed(custom_path, custom)
    print(f'{len(events)} events: {sum(bool(p) for _, p, _ in events)} automatic, '
          f'{sum(not p for _, p, _ in events)} custom')


def main():
    xlsx = Path(sys.argv[1]) if len(sys.argv) > 1 else Path('GameStateEvents.xlsx')
    generate(read_events(xlsx), xlsx.resolve().parent)

if __name__ == '__main__':
    main()
